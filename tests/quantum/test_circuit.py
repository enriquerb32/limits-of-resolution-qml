"""Physics and differentiation checks for the variational circuit used by the hybrid models.

The circuit (``code/modelos_cuanticos._make_qnode``) re-uploads each input angle with
``RY(x) RZ(x)`` in every layer, followed by ``StronglyEntanglingLayers``, and returns
``<Z_i>`` on every qubit. The tests check properties that follow from quantum mechanics,
independently of the implementation:

* expectation values of Pauli-Z lie in [-1, 1];
* batched and per-sample evaluation agree;
* backpropagated gradients equal the exact parameter-shift rule, which holds because every
  trainable angle enters a single rotation generated by a Pauli operator / 2;
* the model is a truncated Fourier series in each input angle with frequencies up to
  ``2 * n_layers`` (Schuld, Sweke & Meyer, 2021): two Pauli-generated encodings per layer.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np
import pytest

pytestmark = pytest.mark.quantum
torch = pytest.importorskip("torch")
pytest.importorskip("pennylane")

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "code"))
from modelos_cuanticos import LstmQNN, _make_qnode  # noqa: E402

N_QUBITS, N_LAYERS = 4, 2


@pytest.fixture(scope="module")
def circuit():  # type: ignore[no-untyped-def]
    return _make_qnode(N_QUBITS, N_LAYERS)


@pytest.fixture
def weights() -> torch.Tensor:
    gen = torch.Generator().manual_seed(0)
    return (torch.rand(N_LAYERS, N_QUBITS, 3, generator=gen, dtype=torch.float64) * 2 - 1) * math.pi


def _expvals(circuit, w: torch.Tensor, x: torch.Tensor) -> torch.Tensor:  # type: ignore[no-untyped-def]
    out = circuit(w, x)
    return torch.stack(list(out), dim=-1) if isinstance(out, list | tuple) else out


def test_expectations_are_bounded(circuit, weights: torch.Tensor) -> None:  # type: ignore[no-untyped-def]
    x = torch.rand(64, N_QUBITS, dtype=torch.float64) * math.pi
    out = _expvals(circuit, weights, x)
    assert out.shape == (64, N_QUBITS)
    assert torch.all(out.abs() <= 1 + 1e-12)


def test_batched_equals_per_sample(circuit, weights: torch.Tensor) -> None:  # type: ignore[no-untyped-def]
    x = torch.rand(8, N_QUBITS, dtype=torch.float64) * math.pi
    batched = _expvals(circuit, weights, x)
    single = torch.stack([_expvals(circuit, weights, xi) for xi in x])
    torch.testing.assert_close(batched, single, rtol=0, atol=1e-12)


def test_backprop_gradient_equals_parameter_shift(circuit, weights: torch.Tensor) -> None:  # type: ignore[no-untyped-def]
    x = torch.tensor([0.3, 1.1, 2.0, 2.7], dtype=torch.float64)
    coeffs = torch.tensor([0.5, -1.0, 0.25, 2.0], dtype=torch.float64)

    def cost(w: torch.Tensor) -> torch.Tensor:
        return (_expvals(circuit, w, x) * coeffs).sum()

    w = weights.clone().requires_grad_(True)
    cost(w).backward()
    assert w.grad is not None

    shift = torch.zeros_like(weights)
    expected = torch.empty_like(weights)
    for idx in np.ndindex(*weights.shape):
        shift.zero_()
        shift[idx] = math.pi / 2
        with torch.no_grad():
            expected[idx] = (cost(weights + shift) - cost(weights - shift)) / 2
    torch.testing.assert_close(w.grad, expected, rtol=0, atol=1e-10)


@pytest.mark.parametrize("wire", range(N_QUBITS))
def test_fourier_spectrum_is_truncated(circuit, weights: torch.Tensor, wire: int) -> None:  # type: ignore[no-untyped-def]
    n_grid = 32
    grid = torch.arange(n_grid, dtype=torch.float64) * 2 * math.pi / n_grid
    x = torch.tensor([0.4, 1.3, 2.2, 0.9], dtype=torch.float64).repeat(n_grid, 1)
    x[:, wire] = grid
    out = _expvals(circuit, weights, x).detach().numpy()
    spectrum = np.abs(np.fft.rfft(out, axis=0)) / n_grid
    max_freq = 2 * N_LAYERS
    assert spectrum[max_freq + 1 :].max() < 1e-12
    assert spectrum[1 : max_freq + 1].max() > 1e-3  # the input actually reaches the readout


def test_hybrid_parameter_count_and_gradient_flow() -> None:
    torch.manual_seed(0)
    model = LstmQNN(in_dim=35, n_q=N_QUBITS, n_l=N_LAYERS)
    n_total = sum(p.numel() for p in model.parameters() if p.requires_grad)
    assert n_total == 2613  # paper: 2,613 trainable parameters
    assert model.W.numel() == 24  # of which 24 quantum

    x = torch.randn(16, 35)
    logits = model(x)
    assert logits.shape == (16,)
    assert torch.isfinite(logits).all()
    logits.sum().backward()
    assert model.W.grad is not None and model.W.grad.abs().sum() > 0
    assert model.lstm.weight_ih_l0.grad is not None and model.lstm.weight_ih_l0.grad.abs().sum() > 0
